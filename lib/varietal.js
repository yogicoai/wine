/**
 * 이름·타입에서 품종을 찾아 기본 맛 축을 만든다.
 * @returns {null | Array<{axis, value}>}
 */
export function guessTasteProfile({ name, type, category } = {}) {
  const text = `${type || ""} ${name || ""}`;

  for (const [clue, values] of VARIETALS) {
    if (clue.test(text)) return AXES.map((axis, i) => ({ axis, value: values[i] }));
  }

  const fallback = BY_CATEGORY[category];
  if (fallback) return AXES.map((axis, i) => ({ axis, value: fallback[i] }));

  return null;
}

/**
 * 같은 품종끼리 묶는 열쇠.
 *
 * 추천 목록에 모스카토만 여덟 개가 나오는 것을 막는 데 쓴다. 짐작한 맛 축은
 * 같은 품종끼리 값이 똑같아서, 점수만으로 세우면 한 품종이 목록을 통째로 차지한다.
 * 타입 문자열은 판매처마다 제각각이라("화이트 와인", "모스카토 다스티") 믿을 수 없고,
 * 맛 축을 정할 때 쓴 것과 같은 규칙으로 판별해야 어긋나지 않는다.
 */
export function varietalKeyOf({ name, type, category } = {}) {
  const text = `${type || ""} ${name || ""}`;
  for (let i = 0; i < VARIETALS.length; i++) {
    if (VARIETALS[i][0].test(text)) return `v${i}`;
  }
  // 품종을 모르면 이름 첫 낱말(대개 생산자)로 묶는다
  return `n:${String(name || "").split(/\s+/)[0] || category || "?"}`;
}
