// 수확은 검색어로 주종을 정한다. 그래서 "와인" 검색에 딸려 온 막걸리가
// wine 으로 들어앉는 일이 생긴다. 이름에 분명한 신호가 있으면 바로잡는다.
//
// 이름이 곧 상품명이라 신호가 꽤 또렷하다 — "장수 생막걸리"를 와인으로 둘 이유가 없다.
// 다만 "와인"이라는 말이 함께 있어도 막걸리는 막걸리다. 신호가 더 구체적인 쪽을 따른다.

// 포도 품종이 적혀 있으면 와인이다. "버번 배럴 카베르네 소비뇽"은 위스키가 아니고,
// 이탈리아 생산자 "스카치아디아볼리"는 스카치가 아니다.
const WINE_GUARD =
  /카베르네|까베르네|메를로|메르로|피노\s*누아|샤르도네|소비뇽\s*블랑|리슬링|시라즈|쉬라즈|진판델|산지오베제|네비올로|말벡|템프라니요|가메|그르나슈|모스카토|프로세코|샴페인|로쏘|비앙코|몬테팔코|키안티|바롤로/;

const RULES = [
  [/막걸리|생탁|탁주|동동주/, "traditional"],
  [/전통주|청명주|약주|법주|청주(?!\s*시)|가양주|전통\s*소주|증류식\s*소주|안동소주|문배주|이강주|한산소곡/, "traditional"],
  [/복분자주|매실주|오미자주|더덕주|인삼주/, "traditional"],
  // "버번 배럴 숙성 진판델"은 와인이다. 통 이름이 뒤따르면 위스키로 보지 않는다.
  [/위스키|싱글\s*몰트|블렌디드\s*몰트|스카치\s*위스키|버번(?!\s*(배럴|베럴|캐스크|오크|barrel|cask))/i, "whisky"],
  [/보드카/, "vodka"],
  [/런던\s*드라이\s*진|드라이\s*진/, "gin"],
  [/데킬라|테킬라/, "tequila"],
  [/다크\s*럼|화이트\s*럼|스파이스드\s*럼/, "rum"],
  // '백주'는 한국 탁주 이름에도 쓰인다(이화백주·양지백주). 중국술 고유 이름만 본다.
  [/고량주|마오타이|수정방|연태고량|우량예|분주/, "baijiu"],
  [/사케|니혼슈|준마이|다이긴조|긴조|니고리/, "sake"],
  [/맥주|라거|에일\b|IPA|스타우트/, "beer"],
];

/**
 * 이름으로 주종을 다시 판단한다.
 * @returns {string|null} 바꿔야 할 주종. 확신할 수 없으면 null(그대로 둔다).
 */
export function recategorize(name) {
  const n = String(name || "");
  if (!n) return null;
  // 포도 품종이 적힌 것은 어떤 규칙에도 넘기지 않는다
  if (WINE_GUARD.test(n)) return null;
  for (const [re, category] of RULES) {
    if (re.test(n)) return category;
  }
  return null;
}
