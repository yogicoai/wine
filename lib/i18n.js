/**
 * UI 문구 — 두 단계를 거친다.
 *   1) 앱의 어휘로 바꾼다 (와인의 "셀러" → 사케의 "술창고")
 *   2) 영어 앱이면 영어로 바꾼다
 * 영어 사전의 열쇠는 와인 기준 원문이므로 그쪽을 먼저 찾고, 없으면 바뀐 말로 찾는다.
 */
// 일본어 사전 — 영어와 같은 열쇠(한국어 원문)를 쓴다.
// 비어 있는 항목은 영어로, 영어도 없으면 한국어로 내려간다.
// 일본어를 읽는 사람에게 한국어를 보여 주는 것보다 영어가 낫다.
const JA = {};

const DICTS = { en: EN, ja: JA };

// 화면 언어는 쿠키가 정한다 (내 정보에서 고른 값).
// 서버가 그린 HTML 과 브라우저가 하이드레이션할 때의 언어가 어긋나면 화면이
// 깨지므로, 언어를 바꿀 때는 새로고침해서 서버가 처음부터 그 언어로 그리게 한다.
// 그래서 여기서는 값을 한 번만 읽어 두면 된다.
let cached = null;

function currentLocale() {
  if (cached) return cached;
  if (typeof document !== "undefined") {
    const m = document.cookie.match(/(?:^|;\s*)bl_locale=([a-z]{2})/);
    if (m && (m[1] === "ko" || m[1] === "en" || m[1] === "ja")) return (cached = m[1]);
  }
  return APP.locale || "ko";
}

/** 서버 컴포넌트용 — 요청의 언어를 받아 그 언어로 옮기는 t 를 만든다 */
export function tFor(locale) {
  return (ko, vars) => translate(ko, vars, locale);
}

function translate(ko, vars, locale) {
  const local = COPY[ko] || ko;
  let out = local;
  if (locale !== "ko") {
    const dict = DICTS[locale];
    // 일본어가 비어 있으면 영어로 — 한국어보다는 읽을 수 있다
    out = dict?.[ko] || dict?.[local] || (locale === "ja" ? EN[ko] || EN[local] : null) || local;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function t(ko, vars) {
  return translate(ko, vars, currentLocale());
}

/** 지금 화면의 언어 — 어법이 언어마다 다른 문장을 조립할 때 쓴다 */
export function uiLocale() {
  return currentLocale();
}

/** 금액 표기 — ko: "12,000원" / en: "₩12,000" / ja: "12,000ウォン" */
export function fmtWon(n) {
  const num = Number(n);
  if (!Number.isFinite(num)) return String(n);
  const locale = currentLocale();
  if (locale === "en") return `₩${num.toLocaleString("en-US")}`;
  if (locale === "ja") return `${num.toLocaleString("ja-JP")}ウォン`;
  return `${num.toLocaleString("ko-KR")}원`;
}

/** 번역 사전에 항목을 더한다 — 화면별 번역을 모듈 분리 없이 한 파일에 모으기 위한 통로 */
export function addMessages(map) {
  Object.assign(EN, map);
}

/** 일본어 사전에 항목을 더한다 */
export function addMessagesJa(map) {
  Object.assign(JA, map);
}

export { EN, JA };

