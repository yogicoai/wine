/**
 * UI 문구 — 두 단계를 거친다.
 *   1) 앱의 어휘로 바꾼다 (와인의 "셀러" → 사케의 "술창고")
 *   2) 영어 앱이면 영어로 바꾼다
 * 영어 사전의 열쇠는 와인 기준 원문이므로 그쪽을 먼저 찾고, 없으면 바뀐 말로 찾는다.
 */
export function t(ko, vars) {
  const local = COPY[ko] || ko;
  let out = APP.locale === "en" ? EN[ko] || EN[local] || local : local;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

/** 금액 표기 — ko: "12,000원" / en: "₩12,000" */
export function fmtWon(n) {
  const num = Number(n);
  if (!Number.isFinite(num)) return String(n);
  return APP.locale === "en"
    ? `₩${num.toLocaleString("en-US")}`
    : `${num.toLocaleString("ko-KR")}원`;
}

