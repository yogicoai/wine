/**
 * @param {{name?, region?, type?, category?}} doc
 * @returns {string|null} 확신할 수 없으면 null — 틀린 국기는 없는 국기보다 나쁘다
 */
export function guessCountry(doc) {
  if (BY_CATEGORY[doc.category]) return BY_CATEGORY[doc.category];

  const text = [doc.name, doc.region, doc.type].filter(Boolean).join(" ");
  if (!text) return null;

  for (const [clue, country] of CLUES) {
    if (clue.test(text)) return country;
  }
  return null;
}
