/**
 * 글자 크기 조절
 *
 * 왜 껐나 — 이 앱의 치수가 px 로 짜여 있어 글자만 키우면 칸이 따라오지 않는다.
 * 그래서 body 에 zoom 을 걸었는데, zoom 은 position:fixed 와 vw/vh 와
 * env(safe-area-inset-*) 를 함께 어긋나게 만든다. 크게로 올리면 배경 레이어와
 * 서랍 덮개가 화면을 덜 덮고, 아래 고정 버튼이 밀린다.
 *
 * 제대로 고치는 길 — globals.css 의 px 치수를 rem 으로 바꾸고 html 의
 * font-size 만 조절한다. 그러면 fixed·vw/vh 가 흔들리지 않는다. 다만 손볼
 * 규칙이 많아 따로 시간을 들여야 한다.
 */
export const FONT_SCALE = process.env.NEXT_PUBLIC_FONT_SCALE === "1";

/**
 * 바코드 스캔
 *
 * 왜 껐나 — 바코드는 상품마다 고유하다(와인마다 다르다). 그래서 "바코드 → 와인"
 * 대조표가 있어야 하는데 공개된 것이 없다. 판매처 검색으로 대신해 보려 했지만
 * 네이버 쇼핑 API 는 바코드 번호로 상품을 찾아 주지 않는다. 와인은 물론이고
 * 칠성사이다·초코파이 같은 일반 상품도 결과가 0건이다(2026-07 실측).
 *
 * 지금 상태로 내보내면 찍을 때마다 "등록되지 않은 바코드"가 뜨고 라벨 촬영으로
 * 되돌아간다. 읽는 것 자체는 정상이라 대조표만 생기면 바로 쓸 수 있다.
 *
 * 켜는 조건 — ① 상용 바코드 DB를 붙이거나 ② 라벨 분석 때 번호를 함께 모아
 * 대조표가 어느 정도 쌓인 뒤. 지금 카탈로그에 연결된 바코드는 1건뿐이다.
 */
export const BARCODE_SCAN = process.env.NEXT_PUBLIC_BARCODE_SCAN === "1";

