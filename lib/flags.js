/** "프랑스", "남아프리카공화국"처럼 표기가 조금 달라도 찾는다. 모르면 null. */
export function flagOf(country) {
  const text = String(country || "");
  if (!text) return null;
  for (const [name, flag] of Object.entries(FLAGS)) {
    if (text.includes(name)) return flag;
  }
  return null;
}
